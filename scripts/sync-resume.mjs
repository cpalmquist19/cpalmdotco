// Brings the resume into this site from the resume repo, where the source of truth lives.
//
//   npm run resume:sync    rebuilds everything from the source
//   npm run resume:check   says whether this repo is behind the source, and changes nothing
//
// The source is cpalm_final.txt in the resume repo. It holds a phone number and an email that must never be
// published, so the script first makes a redacted copy and builds every output from that copy, never from the
// original. It then checks the outputs for the removed details and stops if any got through. It produces:
//   public/resume/Caleb-Palmquist-Resume.docx   built by that repo's own build.js, run on the redacted copy
//   public/resume/Caleb-Palmquist-Resume.txt    the redacted source with its Markdown marks removed
//   public/resume/Caleb-Palmquist-Resume.pdf    printed from HTML by headless Chromium (the one Playwright installs)
//   src/content/resume.generated.ts             the text the chat model reads
//   src/site/experience.ts                      what the Experience and Skills pages show
//
// The outputs are committed, because the deployed site cannot reach the resume repo.
// The resume repo is found next to this one (../resume); set RESUME_REPO to point somewhere else.

import { execFileSync } from "node:child_process";
import { copyFileSync, existsSync, mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "@playwright/test";
import { assertNoPii, parseResume, redactSource, toHtml, toPlainText } from "./resume-render.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SOURCE_DIR = path.resolve(process.env.RESUME_REPO ?? path.join(ROOT, "..", "resume"));
const SOURCE = path.join(SOURCE_DIR, "cpalm_final.txt");
const BUILD_SCRIPT = path.join(SOURCE_DIR, "build.js");

const NAME = "Caleb-Palmquist-Resume";
const PUBLIC_DIR = path.join(ROOT, "public", "resume");
const DOCX = path.join(PUBLIC_DIR, `${NAME}.docx`);
const TXT = path.join(PUBLIC_DIR, `${NAME}.txt`);
const PDF = path.join(PUBLIC_DIR, `${NAME}.pdf`);
const CHAT_TS = path.join(ROOT, "src", "content", "resume.generated.ts");
const EXPERIENCE_TS = path.join(ROOT, "src", "site", "experience.ts");

const rel = (file) => path.relative(ROOT, file).replaceAll("\\", "/");

function fail(message) {
  console.error(message);
  process.exit(1);
}

const GENERATED_NOTE = `// GENERATED by scripts/sync-resume.mjs from cpalm_final.txt in the resume repo. Do not edit it by hand:
// change the source there and run \`npm run resume:sync\`. Personal details are removed before this is written.`;

function chatTs(plain) {
  const escaped = plain.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  return `${GENERATED_NOTE}
export const RESUME_TEXT = \`${escaped}\`;
`;
}

function experienceTs({ summary, employer, roles, projects, skills }) {
  const json = (value) => JSON.stringify(value, null, 2);
  return `${GENERATED_NOTE}
// What the Experience and Skills pages show.

export type Role = { title: string; period: string; highlights: string[] };
export type SideProject = { title: string; meta: string; highlights: string[] };

export const SUMMARY = ${json(summary)};

export const EMPLOYER = ${json(employer)};

// Newest first
export const ROLES: Role[] = ${json(roles)};

export const SIDE_PROJECTS: SideProject[] = ${json(projects)};

export const SKILLS: { group: string; items: string[] }[] = ${json(skills)};
`;
}

const readIfExists = (file) => (existsSync(file) ? readFileSync(file, "utf8") : null);

/** Every text file inside a .docx, joined. A .docx is a zip, so this borrows the zip reader the resume repo already has */
async function docxText(file) {
  const JSZip = createRequire(BUILD_SCRIPT)("jszip");
  const zip = await JSZip.loadAsync(readFileSync(file));
  const parts = Object.values(zip.files).filter((entry) => !entry.dir && /\.(xml|rels)$/.test(entry.name));
  return (await Promise.all(parts.map((entry) => entry.async("string")))).join("\n");
}

async function printPdf(html, file) {
  let browser;
  try {
    browser = await chromium.launch();
  } catch (error) {
    throw new Error(`Could not start Chromium to print the PDF. Install it with: npx playwright install chromium\n${error.message}`);
  }
  try {
    const page = await browser.newPage();
    await page.setContent(html, { waitUntil: "load" });
    await page.emulateMedia({ media: "print" });
    await page.pdf({
      path: file,
      format: "Letter",
      printBackground: true,
      // A tagged PDF carries its structure, so screen readers and applicant-tracking parsers can read it in order
      tagged: true,
      margin: { top: "0.45in", bottom: "0.45in", left: "0.5in", right: "0.5in" },
    });
  } finally {
    await browser.close();
  }
}

if (!existsSync(SOURCE) || !existsSync(BUILD_SCRIPT)) {
  fail(`Could not find cpalm_final.txt and build.js in ${SOURCE_DIR}\nSet RESUME_REPO to the folder that has them.`);
}

// From here on only the redacted copy is used. The original is never written to an output
const original = readFileSync(SOURCE, "utf8");
const { text: source, removed } = redactSource(original);
if (!removed.length) fail("Found no phone number or email in the source to remove. Check that redactSource still matches how the contact line is written.");

const plain = toPlainText(source);
const html = toHtml(source);
const outputs = {
  [rel(TXT)]: plain,
  [rel(CHAT_TS)]: chatTs(plain),
  [rel(EXPERIENCE_TS)]: experienceTs(parseResume(source)),
};
for (const [file, text] of Object.entries(outputs)) assertNoPii(text, file, removed);
assertNoPii(html, "the page the PDF is printed from", removed);

if (process.argv.includes("--check")) {
  const sourceTime = statSync(SOURCE).mtimeMs;
  // The text files are compared by content. The .docx and .pdf are binary and differ on every build, so they are
  // judged by whether they were built after the source last changed. The .docx is also searched for personal details
  const problems = [
    ...Object.entries(outputs).map(([file, text]) => readIfExists(path.join(ROOT, file)) !== text && `${file} differs from the source`),
    ...[DOCX, PDF].map((file) =>
      !existsSync(file) ? `${rel(file)} is missing` : statSync(file).mtimeMs < sourceTime && `${rel(file)} is older than the source`,
    ),
  ];
  if (existsSync(DOCX)) {
    try {
      assertNoPii(await docxText(DOCX), rel(DOCX), removed);
    } catch (error) {
      problems.push(error.message);
    }
  }

  const found = problems.filter(Boolean);
  if (found.length) {
    console.error(`The site is behind the resume:\n- ${found.join("\n- ")}\nRun: npm run resume:sync`);
    process.exit(1);
  }
  console.log("The site's resume is up to date with the source, and holds no personal details.");
  process.exit(0);
}

// Build everything in a scratch folder first, so a failure part-way never leaves the site with a mixed set of files
const scratch = mkdtempSync(path.join(tmpdir(), "resume-sync-"));
try {
  const builtDocx = path.join(scratch, `${NAME}.docx`);
  const builtPdf = path.join(scratch, `${NAME}.pdf`);

  // build.js reads cpalm_final.txt from beside itself, so it runs from a copy that sits next to the redacted source.
  // NODE_PATH lets that copy find the docx package installed in the resume repo
  const buildCopy = path.join(scratch, "build.js");
  copyFileSync(BUILD_SCRIPT, buildCopy);
  writeFileSync(path.join(scratch, "cpalm_final.txt"), source);
  execFileSync(process.execPath, [buildCopy, builtDocx], {
    cwd: scratch,
    env: { ...process.env, NODE_PATH: path.join(SOURCE_DIR, "node_modules") },
    stdio: "pipe",
  });
  assertNoPii(await docxText(builtDocx), "the .docx", removed);
  await printPdf(html, builtPdf);

  copyFileSync(builtDocx, DOCX);
  copyFileSync(builtPdf, PDF);
  for (const [file, text] of Object.entries(outputs)) writeFileSync(path.join(ROOT, file), text);

  // Chromium writes each page as its own /Type /Page object, so counting them gives the length
  const pages = (readFileSync(PDF).toString("latin1").match(/\/Type\s*\/Page(?![s\w])/g) ?? []).length;
  console.log(`Synced from ${SOURCE}`);
  console.log(`Removed ${removed.length} personal details (phone, email) from every output.`);
  for (const file of [DOCX, PDF]) console.log(`  ${rel(file)}`);
  for (const file of Object.keys(outputs)) console.log(`  ${file}`);
  console.log(`The PDF is ${pages} page${pages === 1 ? "" : "s"}. It is checked at the page it is printed from, since its own text is compressed.`);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
